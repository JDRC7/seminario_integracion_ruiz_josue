
# Declaración de variables

nombre = "Roberto Rocha"
edad = 15

print(nombre)
print(edad)

apellido: str = "Rocha"
print(apellido)

print("Tipos de Variables")

# Tipo Texto o String
print("Tipo Texto o String")

nombre_estudiante = "Roberto Rocha"
print(nombre_estudiante)
print(type(nombre_estudiante))

# Tipo de Variable Entera
print("Tipo de Variable Entera")

curso = 10
print(curso)
print(type(curso))

# Tipo de Variable Decimal o Float
print("Tipo de Variable Decimal")

nota_matematicas = 8.5
print(nota_matematicas)
print(type(nota_matematicas))

# Tipo de Variable Booleana
print("Tipo de Variable Booleana")

estudiante_aprobado = True
print(estudiante_aprobado)
print(type(estudiante_aprobado))

# Modificación de variables
print("Modificación de variables")

materias = 5
print(materias)

materias = 5 + 5
print(materias)

materias += 5
print(materias)
